const script = [
  "const wk = window.webkit && window.webkit.messageHandlers && window.webkit.messageHandlers.cu;",
  "function report(event, fields) {",
  "  const row = Object.assign({ event: event }, fields || {});",
  "  if (wk) { wk.postMessage(row); return; }",
  "  fetch('/event', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(row) }).catch(function () {});",
  "}",
  "const field = document.getElementById('web-field');",
  "const scroller = document.getElementById('web-scroll');",
  "const drag = document.getElementById('web-drag');",
  "let lastSelection = '';",
  "function selection() {",
  "  if (document.activeElement !== field) return;",
  "  const key = field.selectionStart + ',' + field.selectionEnd + ',' + field.value.length;",
  "  if (key === lastSelection) return;",
  "  lastSelection = key;",
  "  report('webSelection', { start: field.selectionStart, end: field.selectionEnd, textLength: field.value.length });",
  "}",
  "field.addEventListener('input', function () { report('webValue', { value: field.value }); });",
  "field.addEventListener('focus', function () { report('webFocus', { id: 'web-field' }); });",
  "field.addEventListener('select', selection);",
  "document.addEventListener('selectionchange', selection);",
  "setInterval(selection, 50);",
  "document.addEventListener('keydown', function (e) { report('webKeyDown', { key: e.key, meta: e.metaKey }); }, true);",
  "document.addEventListener('mousedown', function (e) { report('webMouseDown', { id: e.target && e.target.id || '' }); }, true);",
  "document.addEventListener('wheel', function () { report('webWheel', {}); }, { capture: true, passive: true });",
  "document.getElementById('web-button').addEventListener('click', function () { report('webClick', { id: 'web-button' }); });",
  "document.getElementById('web-div').addEventListener('click', function () { report('webClick', { id: 'web-div' }); });",
  "let lastTop = -1;",
  "scroller.addEventListener('scroll', function () {",
  "  const top = Math.round(scroller.scrollTop);",
  "  if (top !== lastTop) { lastTop = top; report('webScroll', { top: top }); }",
  "});",
  "function region(x) {",
  "  const rect = drag.getBoundingClientRect();",
  "  if (x < rect.left + rect.width / 3) return 'A';",
  "  if (x > rect.left + rect.width * 2 / 3) return 'B';",
  "  return 'mid';",
  "}",
  "let dragStart = null;",
  "let dragMoves = 0;",
  "drag.addEventListener('mousedown', function (e) { dragStart = region(e.clientX); dragMoves = 0; e.preventDefault(); });",
  "document.addEventListener('mousemove', function () { if (dragStart) dragMoves += 1; });",
  "document.addEventListener('mouseup', function (e) {",
  "  if (!dragStart) return;",
  "  report('webDrag', { startRegion: dragStart, endRegion: region(e.clientX), moves: dragMoves });",
  "  dragStart = null;",
  "});",
  "window.cuReset = function (seq, text) {",
  "  if (document.activeElement && document.activeElement.blur) document.activeElement.blur();",
  "  const selected = window.getSelection();",
  "  if (selected) selected.removeAllRanges();",
  "  field.value = text;",
  "  lastSelection = '';",
  "  scroller.scrollTop = 360;",
  "  lastTop = Math.round(scroller.scrollTop);",
  "  dragStart = null;",
  "  report('webReset', { seq: seq, top: lastTop });",
  "};",
  "async function control() {",
  "  let after = 0;",
  "  for (;;) {",
  "    try {",
  "      const reply = await fetch('/control?after=' + after);",
  "      const command = await reply.json();",
  "      if (command.seq) {",
  "        after = command.seq;",
  "        window.cuReset(command.seq, command.text || '');",
  "        report('resetDone', { seq: command.seq });",
  "      }",
  "    } catch (error) {",
  "      await new Promise(function (done) { setTimeout(done, 200); });",
  "    }",
  "  }",
  "}",
  "if (!wk) { control(); report('webReady', {}); }",
].join("\n");

