import * as fs from "node:fs";
import * as path from "node:path";
import { isWindowsPath } from "./path-utils.ts";
import { BoundedLruCache } from "./bounded-cache.ts";

const DEFAULT_HEADER_BYTES = 4096;

const GENERATED_DIR_NAMES = new Set([
  "generated",
  "__generated__",
  "codegen",
  "__codegen__",
  "generated-sources",
  "generated_sources",
  "dist",
  "openapi-generated",
  ".openapi-generator",
]);

const GENERATED_HEADER_PATTERNS = [
  /@generated\b/i,
  /@ts-nocheck\b/i,
  /\bcode generated\b/i,
  /\bdo not edit\b/i,
  /\bautomatically generated\b/i,
  /\bthis file was generated\b/i,
  /\bgenerated by protoc\b/i,
  /\bgenerated by graphql-code-generator\b/i,
  /\bgenerated by openapi-generator\b/i,
  /\bgenerated by swagger codegen\b/i,
];

const LOCKFILE_NAMES = new Set([
  "package-lock.json",
  "packages.lock.json",
  "npm-shrinkwrap.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "bun.lock",
  "cargo.lock",
  "composer.lock",
  "gemfile.lock",
  "poetry.lock",
  "uv.lock",
  "go.sum",
]);

const GENERATED_FILE_PATTERNS = [
  /(^|[._-])generated([._-]|$)/i,
  /(^|[._-])gen([._-])/i,
  /_generated\.(go|rs|py|rb|java|kt|ts|tsx|js|jsx|mjs|cjs)$/i,
  /_gen\.(go|rs|py|rb|java|kt|ts|tsx|js|jsx|mjs|cjs)$/i,
  /\.pb\.(go|ts|tsx|js|jsx|mjs|cjs)$/i,
  /_pb2(_grpc)?\.py$/i,
  /\.sql\.(go|ts|js)$/i,
  /_sqlc\.go$/i,
  /\.g\.([jt]sx?|mjs|cjs|rs|go)$/i,
];

const MINIFIED_BUNDLE_FILE_PATTERNS = [
  /\.min\.(js|mjs|cjs|css)$/i,
  /\.(bundle|chunk)\.(js|mjs|cjs|css)$/i,
];

const DECLARATION_FILE_PATTERNS = [/\.d\.ts$/i, /\.d\.mts$/i, /\.d\.cts$/i];

export interface GeneratedArtifactOptions {
  content?: string;
  readContentHeader?: boolean;
  maxHeaderBytes?: number;
  includeDeclarations?: boolean;
}

function pathSegments(filePath: string): string[] {
  return path
    .normalize(filePath)
    .split(/[\\/]+/)
    .filter(Boolean);
}

function generatedBasename(filePath: string): string {
  return isWindowsPath(filePath) ? path.win32.basename(filePath) : path.basename(filePath);
}

export function isGeneratedArtifactDirectoryName(dirName: string): boolean {
  return GENERATED_DIR_NAMES.has(dirName.trim().toLowerCase());
}

export function isDeclarationFile(filePath: string): boolean {
  const base = generatedBasename(filePath).toLowerCase();
  return DECLARATION_FILE_PATTERNS.some((pattern) => pattern.test(base));
}

function hasStrongGeneratedArtifactPath(filePath: string): boolean {
  const segments = pathSegments(filePath);
  const dirSegments = segments.slice(0, -1);
  if (dirSegments.some((segment) => isGeneratedArtifactDirectoryName(segment))) {
    return true;
  }

  const base = generatedBasename(filePath);
  if (LOCKFILE_NAMES.has(base.toLowerCase())) return true;
  return MINIFIED_BUNDLE_FILE_PATTERNS.some((pattern) => pattern.test(base));
}

function hasWeakGeneratedFileNamePattern(filePath: string): boolean {
  const base = generatedBasename(filePath);
  return GENERATED_FILE_PATTERNS.some((pattern) => pattern.test(base));
}

function hasGeneratedArtifactContent(content: string): boolean {
  const header = content.slice(0, DEFAULT_HEADER_BYTES);
  return GENERATED_HEADER_PATTERNS.some((pattern) => pattern.test(header));
}

const HEADER_VERDICT_MEMO_CAP = 50_000;
const headerVerdictMemo = new BoundedLruCache<string, boolean>(HEADER_VERDICT_MEMO_CAP);

export function _resetGeneratedArtifactCaches(): void {
  headerVerdictMemo.clear();
}

function readFileHeader(filePath: string, maxBytes = DEFAULT_HEADER_BYTES): string | undefined {
  let fd: number | undefined;
  try {
    fd = fs.openSync(filePath, "r");
    const buffer = Buffer.alloc(Math.max(0, maxBytes));
    const bytesRead = fs.readSync(fd, buffer, 0, buffer.length, 0);
    return buffer.toString("utf8", 0, bytesRead);
  } catch {
    return undefined;
  } finally {
    if (fd !== undefined) {
      try {
        fs.closeSync(fd);
      } catch {}
    }
  }
}

function fileHeaderLooksGenerated(filePath: string, maxBytes: number): boolean {
  let key: string;
  try {
    const st = fs.statSync(filePath);
    key = `${st.mtimeMs}:${st.size}:${maxBytes}:${filePath}`;
  } catch {
    return false;
  }
  const cached = headerVerdictMemo.get(key);
  if (cached !== undefined) return cached;
  const header = readFileHeader(filePath, maxBytes);
  const verdict = header !== undefined && hasGeneratedArtifactContent(header);
  headerVerdictMemo.set(key, verdict);
  return verdict;
}

export type GeneratedArtifactVerdict = "generated" | "override" | "clean";

export type GeneratedArtifactEvidence = "strong" | "content" | "name-only";

export interface GeneratedArtifactClassification {
  verdict: GeneratedArtifactVerdict;
  evidence?: GeneratedArtifactEvidence;
}

export function classifyGeneratedOrArtifactDetailed(
  filePath: string,
  options: GeneratedArtifactOptions = {},
): GeneratedArtifactClassification {
  if (hasStrongGeneratedArtifactPath(filePath)) {
    return { verdict: "generated", evidence: "strong" };
  }
  if (options.includeDeclarations && isDeclarationFile(filePath)) {
    return { verdict: "generated", evidence: "strong" };
  }

  const weakNameMatch = hasWeakGeneratedFileNamePattern(filePath);

  if (options.content !== undefined) {
    if (hasGeneratedArtifactContent(options.content)) {
      return { verdict: "generated", evidence: "content" };
    }
    return { verdict: weakNameMatch ? "override" : "clean" };
  }

  if (options.readContentHeader) {
    if (fileHeaderLooksGenerated(filePath, options.maxHeaderBytes ?? DEFAULT_HEADER_BYTES)) {
      return { verdict: "generated", evidence: "content" };
    }
    return { verdict: weakNameMatch ? "override" : "clean" };
  }

  return weakNameMatch ? { verdict: "generated", evidence: "name-only" } : { verdict: "clean" };
}

export function classifyGeneratedOrArtifact(
  filePath: string,
  options: GeneratedArtifactOptions = {},
): GeneratedArtifactVerdict {
  return classifyGeneratedOrArtifactDetailed(filePath, options).verdict;
}

export function isGeneratedOrArtifact(
  filePath: string,
  options: GeneratedArtifactOptions = {},
): boolean {
  return classifyGeneratedOrArtifact(filePath, options) === "generated";
}
